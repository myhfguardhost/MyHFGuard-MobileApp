    fun translate(text: String, language: AppLanguageCode): String {
        val exact = when (language) {
            AppLanguageCode.MANDARIN -> ZH[text]
            AppLanguageCode.TAMIL -> TA[text]
            else -> null
        }
        if (exact != null) return exact
        return translateDynamic(text, language)
    }

    private fun translateDynamic(text: String, language: AppLanguageCode): String {
        val zh = language == AppLanguageCode.MANDARIN
        val ta = language == AppLanguageCode.TAMIL
        if (!zh && !ta) return text

        Regex("^Goal save failed: (.+)$").matchEntire(text)?.let {
            return if (zh) "目标保存失败：${it.groupValues[1]}" else "இலக்கைச் சேமிக்க முடியவில்லை: ${it.groupValues[1]}"
        }
        Regex("^Rating save failed: (.+)$").matchEntire(text)?.let {
            return if (zh) "评分保存失败：${it.groupValues[1]}" else "மதிப்பீட்டைச் சேமிக்க முடியவில்லை: ${it.groupValues[1]}"
        }
        Regex("^(.+) data can be entered and shown in the app\\. Full graphs remain on the website\\.$").matchEntire(text)?.let {
            val module = translate(it.groupValues[1], language)
            return if (zh) "可在应用中输入和查看${module}数据。完整图表仍可在网站查看。" else "${module} தரவை செயலியில் உள்ளிட்டு பார்க்கலாம். முழு வரைபடங்கள் இணையதளத்தில் கிடைக்கும்."
        }
        Regex("^This week's goal will be set to: (.+)$").matchEntire(text)?.let {
            return if (zh) "本周目标将设为：${it.groupValues[1]}" else "இந்த வார இலக்கு: ${it.groupValues[1]}"
        }
        Regex("^Week of (.+)$").matchEntire(text)?.let {
            return if (zh) "本周开始于 ${it.groupValues[1]}" else "${it.groupValues[1]} தொடங்கும் வாரம்"
        }
        Regex("^(\\d+) steps remaining$").matchEntire(text)?.let {
            return if (zh) "还差 ${it.groupValues[1]} 步" else "${it.groupValues[1]} நடைகள் மீதமுள்ளன"
        }
        Regex("^(\\d+) steps$").matchEntire(text)?.let {
            return if (zh) "${it.groupValues[1]} 步" else "${it.groupValues[1]} நடைகள்"
